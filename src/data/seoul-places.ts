const DAYS: readonly Weekday[] = [
  "sun",
  "mon",
  "tue",
  "wed",
  "thu",
  "fri",
  "sat",
]

const PEOPLE: readonly Companion[] = ["solo", "couple", "children", "parents"]
const EVERYONE: readonly Companion[] = [...PEOPLE, "pet"]

function weeklyHours(
  open: string,
  close: string,
  closed: readonly Weekday[] = [],
  lastAdmissionMinutesBeforeClose?: number,
): WeeklyOpeningHours {
  return Object.fromEntries(
    DAYS.map((day) => [
      day,
      closed.includes(day)
        ? []
        : [
            {
              open,
              close,
              ...(lastAdmissionMinutesBeforeClose === undefined
                ? {}
                : { lastAdmissionMinutesBeforeClose }),
            },
          ],
    ]),
  ) as unknown as WeeklyOpeningHours
}

function selectedDayHours(
  days: readonly Weekday[],
  open: string,
  close: string,
): WeeklyOpeningHours {
  return Object.fromEntries(
    DAYS.map((day) => [day, days.includes(day) ? [{ open, close }] : []]),
  ) as unknown as WeeklyOpeningHours
}

